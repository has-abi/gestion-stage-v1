package com.gestion.stage.utils;

public class Convention {
	
	private String organisme_nom;
	private String organisme_adress;
	private String organisme_tele;
	public String getOrganisme_nom() {
		return organisme_nom;
	}
	public void setOrganisme_nom(String organisme_nom) {
		this.organisme_nom = organisme_nom;
	}
	public String getOrganisme_adress() {
		return organisme_adress;
	}
	public void setOrganisme_adress(String organisme_adress) {
		this.organisme_adress = organisme_adress;
	}
	public String getOrganisme_tele() {
		return organisme_tele;
	}
	public void setOrganisme_tele(String organisme_tele) {
		this.organisme_tele = organisme_tele;
	} 
	

	

}
